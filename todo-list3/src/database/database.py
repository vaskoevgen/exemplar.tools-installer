def execute_init_script(
    connection_config: ConnectionConfig,
    event_handler=None,
    log_handler=None,
) -> InitScriptResult:
    """Execute the idempotent init.sql script against the target PostgreSQL database."""
    _emit = event_handler or (lambda event: None)
    _log_h = log_handler or (lambda level, msg, ctx: None)

    _emit({
        "pact_key": "PACT:3549b0:database:execute_init_script",
        "event": "invoked",
        "input_classification": ["connection_config"],
        "output_classification": [],
        "side_effects": [],
        "ts": time.time_ns(),
    })

    _log("info", "Executing init script")

    try:
        conn = psycopg2.connect(connection_config.database_url)
        try:
            conn.autocommit = True
            with conn.cursor() as cur:
                cur.execute(INIT_SQL)
            result = InitScriptResult(
                table_created=True,
                trigger_created=True,
                check_constraint_present=True,
            )
        finally:
            conn.close()
    except (ConnectionError, AuthenticationError, DatabaseNotFoundError,
            SQLSyntaxError, PermissionError):
        raise
    except Exception as exc:
        _classify_and_raise(exc)
        # unreachable but satisfies type checker
        raise  # pragma: no cover

    _emit({
        "pact_key": "PACT:3549b0:database:execute_init_script",
        "event": "completed",
        "input_classification": ["connection_config"],
        "output_classification": ["init_script_result"],
        "side_effects": ["schema_created"],
        "ts": time.time_ns(),
    })

    _log("info", "Init script executed successfully")
    return result


def verify_schema(
    connection_config: ConnectionConfig,
    event_handler=None,
    log_handler=None,
) -> InitScriptResult:
    """Verify the database schema by introspecting information_schema and pg_catalog."""
    _emit = event_handler or (lambda event: None)
    _log_h = log_handler or (lambda level, msg, ctx: None)

    _emit({
        "pact_key": "PACT:3549b0:database:verify_schema",
        "event": "invoked",
        "input_classification": ["connection_config"],
        "output_classification": [],
        "side_effects": [],
        "ts": time.time_ns(),
    })

    _log("info", "Verifying database schema")

    table_exists = False
    check_constraint_present = False
    trigger_exists = False

    try:
        conn = psycopg2.connect(connection_config.database_url)
        try:
            conn.autocommit = True
            with conn.cursor() as cur:
                # 1. Check if table exists
                cur.execute(
                    "SELECT EXISTS ("
                    "  SELECT 1 FROM information_schema.tables "
                    "  WHERE table_schema = 'public' AND table_name = 'tasks'"
                    ")"
                )
                row = cur.fetchone()
                table_exists = bool(row and row[0])

                # 2. Check if CHECK constraint exists
                cur.execute(
                    "SELECT EXISTS ("
                    "  SELECT 1 FROM information_schema.check_constraints "
                    "  WHERE constraint_name = 'tasks_status_check'"
                    ")"
                )
                row = cur.fetchone()
                check_constraint_present = bool(row and row[0])

                # 3. Check if trigger exists
                cur.execute(
                    "SELECT EXISTS ("
                    "  SELECT 1 FROM pg_trigger "
                    "  WHERE tgname = 'set_updated_at'"
                    ")"
                )
                row = cur.fetchone()
                trigger_exists = bool(row and row[0])
        finally:
            conn.close()
    except (ConnectionError, AuthenticationError, DatabaseNotFoundError,
            SQLSyntaxError, PermissionError):
        raise
    except Exception as exc:
        _classify_and_raise(exc)
        raise  # pragma: no cover

    result = InitScriptResult(
        table_created=table_exists,
        trigger_created=trigger_exists,
        check_constraint_present=check_constraint_present,
    )

    _emit({
        "pact_key": "PACT:3549b0:database:verify_schema",
        "event": "completed",
        "input_classification": ["connection_config"],
        "output_classification": ["init_script_result"],
        "side_effects": [],
        "ts": time.time_ns(),
    })

    _log("info", f"Schema verification complete: {result}")
    return result


