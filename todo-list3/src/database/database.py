@dataclass
class TaskRow:
    """Represents a single row in the tasks table as returned by SELECT *."""
    id: object  # TaskId or int
    title: object  # TaskTitle or str
    description: object = None  # TaskDescription or Optional[str]
    status: object = None  # TaskStatus or str
    created_at: object = None  # Timestamptz or datetime
    updated_at: object = None  # Timestamptz or datetime


@dataclass(frozen=True)
class ConnectionConfig:
    """PostgreSQL connection parameters derived from DATABASE_URL."""
    database_url: str
    port: int

    def __post_init__(self) -> None:
        if not isinstance(self.database_url, str) or not self.database_url.startswith("postgresql://"):
            raise ValueError(
                f"database_url must start with 'postgresql://', got: {self.database_url!r}"
            )
        if self.port != 5432:
            raise ValueError(f"port must be exactly 5432, got: {self.port}")


@dataclass
class InitScriptResult:
    """Result of executing the init.sql script against a PostgreSQL instance."""
    table_created: bool
    trigger_created: bool
    check_constraint_present: bool


# ---------------------------------------------------------------------------
# SQL Init Script
# ---------------------------------------------------------------------------

INIT_SQL = """
-- Idempotent init script for tasks table
-- Safe to re-execute: uses IF NOT EXISTS and OR REPLACE throughout

-- 1. Create the tasks table if it does not exist
CREATE TABLE IF NOT EXISTS tasks (
    id SERIAL PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Add CHECK constraint on status column (idempotent via DO block)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.check_constraints
        WHERE constraint_name = 'tasks_status_check'
    ) THEN
        ALTER TABLE tasks
            ADD CONSTRAINT tasks_status_check
            CHECK (status IN ('pending', 'in_progress', 'done'));
    END IF;
END
$$;

-- 3. Create or replace the trigger function
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 4. Create trigger if not exists (idempotent via DO block)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'set_updated_at'
    ) THEN
        CREATE TRIGGER set_updated_at
            BEFORE UPDATE ON tasks
            FOR EACH ROW
            EXECUTE FUNCTION update_updated_at_column();
    END IF;
END
$$;
"""


# ---------------------------------------------------------------------------
# Helper: classify psycopg2 errors and re-raise as contract errors
# ---------------------------------------------------------------------------

def _classify_and_raise(exc: Exception) -> None:
    """Classify a psycopg2 exception into the contract error hierarchy."""
    msg = str(exc).lower()

    _log("error", f"Database error: {exc}")

    if isinstance(exc, psycopg2.OperationalError):
        if "password authentication failed" in msg or "authentication failed" in msg:
            raise AuthenticationError(str(exc)) from exc
        if "does not exist" in msg and "database" in msg:
            raise DatabaseNotFoundError(str(exc)) from exc
        # Default OperationalError -> connection issue
        raise ConnectionError(str(exc)) from exc

    if isinstance(exc, psycopg2.ProgrammingError):
        if "permission denied" in msg:
            raise PermissionError(str(exc)) from exc
        if "syntax error" in msg:
            raise SQLSyntaxError(str(exc)) from exc
        # ProgrammingError with permission denied
        raise PermissionError(str(exc)) from exc

    if isinstance(exc, psycopg2.Error):
        raise ConnectionError(str(exc)) from exc

    # Re-raise unknown
    raise exc


